"""Текст ПОСТАВЛЯЕМОГО бандла без комментариев — для текстовых гейтов.

Зачем. Гейты `§−91`/`§−97` ищут в `src/premium_assets/*.js` литералы, которых
там быть не должно: зашитый счётчик, литеральный статус, вымышленное имя банка.
Ищут они по СЫРОМУ тексту файла, а Babel сохраняет комментарии — поэтому
разбор дефекта, написанный в комментарии рядом с починкой, валил тот самый
гейт, который эту починку и охраняет. Дважды за один раунд.

Это не придирка к формулировкам: гейт, который срабатывает на объяснении
дефекта, учит обходить себя молчанием, то есть удалять из кода именно те
записи, ради которых проект ведёт журнал.

Комментарий до глаз читателя не доходит — до них доходит КОД. Здесь
комментарии убираются, а строковые литералы сохраняются как есть: литерал
внутри строки — настоящее нарушение, литерал внутри `//` — документация.
"""

from __future__ import annotations

__all__ = ["code_only"]


def code_only(js: str) -> str:
    """JS-исходник без комментариев; строки и их содержимое не тронуты.

    Разбор посимвольный, а не регулярным выражением: `"https://x"` содержит
    `//` внутри строки, и наивная регулярка отрезала бы половину файла — то
    есть гейт стал бы «зелёным» просто потому, что перестал видеть код.
    """
    out: list[str] = []
    i, n = 0, len(js)
    quote: str | None = None          # активная кавычка строки
    while i < n:
        ch = js[i]
        nxt = js[i + 1] if i + 1 < n else ""

        if quote is not None:
            out.append(ch)
            if ch == "\\":                     # экранированный символ — целиком
                if i + 1 < n:
                    out.append(js[i + 1])
                    i += 2
                    continue
            elif ch == quote:
                quote = None
            i += 1
            continue

        if ch in ("'", '"', "`"):
            quote = ch
            out.append(ch)
            i += 1
            continue

        if ch == "/" and nxt == "/":
            while i < n and js[i] != "\n":
                i += 1
            continue

        if ch == "/" and nxt == "*":
            i += 2
            while i + 1 < n and not (js[i] == "*" and js[i + 1] == "/"):
                i += 1
            i += 2
            # Комментарий мог занимать строки — оставляем перевод строки, чтобы
            # номера строк в диагностике не съезжали слишком сильно.
            out.append("\n")
            continue

        out.append(ch)
        i += 1
    return "".join(out)
