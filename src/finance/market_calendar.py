"""
Рынок, валюта котировки и торговый календарь инструмента (MP-08.5, ЧК-08.5-1).

Зачем отдельный модуль
──────────────────────
До ручного портфеля у проекта был ровно один рынок и ровно одна валюта цен, и
знание об этом было размазано по коду в виде допущений: «неделя — это пн–пт»,
«если суффикса нет, это США», «просрочка считается в календарных днях».  Каждое
из этих допущений ЛОЖНО хотя бы для одного рынка, который приедет уже с первой
выгрузкой Stooq:

* крипто (`BTC.V`) торгуется **7/7** — субботний бар там норма, а не аномалия;
* саудовские индексы (`^TASI`, `^MT30`, `^NOMUC`) исчезают **в пятницу**: их
  биржа работает вс–чт (замерено на срезах 2026-08-06/07, `STOOQ_CONVENTION §3.8.7`);
* японская бумага котируется в JPY, лондонская — в GBP.

Поэтому рынок и валюта — **факты об инструменте**, а не про суффикс в коде
потребителя, а календарь **выводится из данных**, а не берётся из списка
праздников: список праздников NYSE не знает про Эр-Рияд, а множество дат, по
которым на рынке были бары, знает.

Слой
────
L0 Cross: модуль НЕ знает про SQLite, про Stooq и про движок.  Сессии рынка
приходят параметром — списком дат.  Это делает его проверяемым без базы и
пригодным для любого будущего источника.
"""

from __future__ import annotations

import bisect
import logging
import re
from typing import Iterable, Sequence

logger = logging.getLogger(__name__)

#: Рынок, который не удалось определить.  Отдельное значение существует ради
#: правила «неизвестное не притворяется известным»: молчаливая подстановка США
#: — тот же класс дефекта, что `provider_for_source`, тихо отдававший
#: брокерский фид неизвестному источнику (A-3, `AUDIT §−73`).
UNKNOWN_MARKET = "UNKNOWN"
UNKNOWN_CURRENCY = "UNKNOWN"

#: Рынок, у которого нет своего инструментального смысла: индексы и FX-пары.
#: Движок их не запрашивает, ingest их не грузит — но отличать их от «не смог
#: разобрать» обязательно, иначе счётчик отбраковки перестанет что-либо значить.
NON_INSTRUMENT = "NON_INSTRUMENT"

#: SSOT форм источника: суффикс Stooq → (рынок, валюта котировки).
#:
#: 🔴 Единственное место, где живёт это соответствие.  Второй словарь где-нибудь
#: в провайдере — это ловушка Т-4 («второй справочник тикеров»): два списка
#: расходятся молча, и расхождение видно только в цифрах отчёта.
#:
#: Значения ИЗМЕРЕНЫ там, где были файлы (`US`, `V`), и объявлены как гипотеза
#: там, где файлов не было (`UK`, `DE`, `JP`, …): мировой пакет `d_world_txt`
#: ещё не качали.  Гипотеза помечена в тесте, а не только в комментарии.
_SUFFIX_TO_MARKET: dict[str, tuple[str, str]] = {
    # ── измерено на дневных срезах 2026-08-06…08 ──
    "US": ("US", "USD"),
    "V": ("CRYPTO", "USD"),
    # ── гипотезы: суффиксы известны по документации Stooq, файлов ещё нет ──
    "UK": ("UK", "GBP"),
    "DE": ("DE", "EUR"),
    "F": ("DE", "EUR"),
    "JP": ("JP", "JPY"),
    "PL": ("PL", "PLN"),
    "HU": ("HU", "HUF"),
    "KZ": ("KZ", "KZT"),
}

#: Календарь рынка: сколько сессий в неделю ОЖИДАЕТСЯ.  Нужен ровно одному
#: потребителю — предупреждению «файл подозрительно мал»; для расчёта просрочки
#: используются РЕАЛЬНЫЕ сессии, а не это число.
_EXPECTED_SESSIONS_PER_WEEK = {"CRYPTO": 7}
_DEFAULT_SESSIONS_PER_WEEK = 5

#: Валюта, в которой котируется рынок, если инструмент не сказал иного.
_MARKET_CURRENCY = {market: ccy for market, ccy in _SUFFIX_TO_MARKET.values()}

#: Символ выгрузки: буквы, цифры, точка, дефис; индекс начинается с `^`.
#: Ведущий `^` разрешён СПЕЦИАЛЬНО — иначе индексы отбраковывались бы как
#: «битый символ» и терялись бы в счётчике вместе с настоящим мусором, то есть
#: сводка перестала бы отличать осознанный пропуск от порчи файла.
_SYMBOL_RE = re.compile(r"^\^?[A-Z0-9][A-Z0-9._-]*$")


def split_symbol(source_symbol: str) -> tuple[str, str]:
    """`'AAPL.US'` → `('AAPL', 'US')`; `'EURUSD'` → `('EURUSD', '')`.

    Разбор по ПОСЛЕДНЕЙ точке: у Stooq встречается `1INCH.V`, где точка одна, и
    гипотетически возможны составные имена.  Класс акции источник пишет через
    дефис (`brk-b.us`), а не точкой, поэтому `rpartition` здесь безопасен —
    замерено на 75 тикерах с дефисом (`STOOQ_CONVENTION §3.7`).
    """
    text = str(source_symbol or "").strip().upper()
    base, _, suffix = text.rpartition(".")
    return (base, suffix) if base else (text, "")


def market_of(source_symbol: str) -> str:
    """Рынок инструмента по форме символа ИСТОЧНИКА.

    Возвращает `NON_INSTRUMENT` для индексов (`^DAX`) и FX-пар (`EURUSD`), и
    `UNKNOWN_MARKET` для всего, чего не знает.  Тихо подставлять `US` нельзя:
    неизвестная бумага получила бы американский торговый календарь и доллар в
    качестве валюты — оба утверждения были бы выдуманы.
    """
    text = str(source_symbol or "").strip().upper()
    if not text:
        return UNKNOWN_MARKET
    if text.startswith("^"):
        return NON_INSTRUMENT
    _base, suffix = split_symbol(text)
    if not suffix:
        # Ни суффикса, ни `^`: у Stooq это валютные пары и ставки — замерено,
        # 95 таких строк в срезе, все вида `EURUSD`/`XAUUSD`/`HUOHUF1M`.
        return NON_INSTRUMENT
    known = _SUFFIX_TO_MARKET.get(suffix)
    return known[0] if known else UNKNOWN_MARKET


def is_known_suffix(suffix: str) -> bool:
    """Знаем ли мы биржевой суффикс источника.

    Публично, потому что нужно ВТОРОМУ модулю — построителю форм символа
    (`finance.stooq_symbols`): он обязан отличать «суффикс биржи» от «класса
    акции» (`BRK.B`).  Приватное имя между модулями не ходит
    (`tests/test_layering.py`), а второй словарь суффиксов был бы ловушкой Т-4.
    """
    return str(suffix or "").strip().upper() in _SUFFIX_TO_MARKET


def known_suffixes() -> frozenset[str]:
    """Все известные биржевые суффиксы источника — для тестов и сводок."""
    return frozenset(_SUFFIX_TO_MARKET)


def currency_of(market: str) -> str:
    """Валюта котировки рынка.  Неизвестный рынок → `UNKNOWN_CURRENCY`.

    🔴 `UNKNOWN` возвращается ИМЕННО как значение, а не как `'USD'`: доллар по
    умолчанию означал бы, что японская бумага молча посчитается по своей цене в
    иенах как по долларовой.  Т-5 («никакого молчаливого курса 1.0») — про то
    же самое, только на шаг позже по конвейеру.
    """
    return _MARKET_CURRENCY.get(str(market or "").strip().upper(),
                                UNKNOWN_CURRENCY)


def currency_of_symbol(source_symbol: str) -> str:
    """Валюта котировки инструмента — сквозной путь `символ → рынок → валюта`."""
    return currency_of(market_of(source_symbol))


def expected_sessions_per_week(market: str) -> int:
    """Сколько торговых дней в неделе ОЖИДАЕТСЯ на этом рынке (7 у крипты)."""
    return _EXPECTED_SESSIONS_PER_WEEK.get(str(market or "").upper(),
                                           _DEFAULT_SESSIONS_PER_WEEK)


def is_valid_symbol(source_symbol: str) -> bool:
    """Символ выглядит как символ, а не как обрывок строки или HTML капчи."""
    return bool(_SYMBOL_RE.match(str(source_symbol or "").strip().upper()))


# ── Календарь: сессии приходят снаружи ───────────────────────────────────────

def sessions_after(sessions: Sequence[int], after: int, *, until: int) -> int:
    """Сколько сессий рынка прошло в интервале `(after, until]`.

    `sessions` — ОТСОРТИРОВАННЫЙ список дат рынка в форме `YYYYMMDD`.  Он и есть
    календарь: множество дат, по которым на этом рынке вообще были бары.
    Праздники, полудни и чужие выходные учтены тем, что их в списке нет.
    """
    if not sessions:
        return 0
    lo = bisect.bisect_right(sessions, int(after))
    hi = bisect.bisect_right(sessions, int(until))
    return max(0, hi - lo)


def staleness_trading_days(sessions: Sequence[int], last_seen: int, *,
                           as_of: int) -> int:
    """Возраст последнего бара бумаги в ТОРГОВЫХ днях её рынка.

    Почему не в календарных.  Замер `tph.us`: последний бар 2026-05-13, бумага
    исчезла из срезов совсем.  На длинных выходных календарный счёт даёт
    ложную просрочку у ЖИВЫХ бумаг, а у мёртвых занижает разницу между «рынок
    отдыхал» и «бумага молчит».  Торговые дни рынка отвечают на нужный вопрос:
    сколько раз рынок торговал, а этой бумаги не было.

    Возвращает 0, когда бар за `as_of` есть.
    """
    return sessions_after(sessions, int(last_seen), until=int(as_of))


def normalise_sessions(dates: Iterable[int]) -> list[int]:
    """Отсортированный список уникальных дат — вход для функций календаря."""
    return sorted({int(d) for d in dates})
