_TRADING_DAYS_PER_YEAR = 252


def demo_tickers() -> list[str]:
    """Резолвленные тикеры, для которых витрина умеет строить ряды."""
    return list(_SPEC.keys())


def _demo_index() -> pd.DatetimeIndex:
    """Фиксированный календарь витрины: рабочие дни, заканчиваются DEMO_END_DATE."""
    return pd.bdate_range(end=pd.Timestamp(DEMO_END_DATE), periods=DEMO_TRADING_DAYS)


def demo_price_matrix(tickers: list[str] | None = None,
                      *, days: int | None = None) -> pd.DataFrame:
    """
    Детерминированная матрица цен витрины.

    Одинакова при любом вызове, на любой машине, в любой день — от аргументов
    зависит только НАБОР колонок и длина хвоста, но не сами значения: ряды
    порождаются от фиксированного зерна и обрезаются с конца.

    Неизвестные тикеры молча пропускаются — витрина не обязана уметь всё;
    вызывающий код и так переживает отсутствующую колонку.
    """
    index = _demo_index()
    rng = np.random.Generator(np.random.PCG64(DEMO_SEED))

    # Общий рыночный шок — один на всю витрину, поэтому берётся ПЕРВЫМ и всегда,
    # независимо от запрошенного набора: иначе корреляции поедут от состава.
    n = len(index)
    mkt_spec = _SPEC["SPY.US"]
    mkt_daily = (mkt_spec[1] / _TRADING_DAYS_PER_YEAR
                 + mkt_spec[2] / np.sqrt(_TRADING_DAYS_PER_YEAR)
                 * rng.standard_normal(n))

    wanted = list(_SPEC.keys()) if tickers is None else [
        t for t in _SPEC if t in set(tickers)
    ]

    cols: dict[str, np.ndarray] = {}
    # Порядок обхода — ВСЕГДА полный `_SPEC`, чтобы поток случайных чисел не
    # зависел от того, какие тикеры запросили: иначе один и тот же тикер получал
    # бы разные ряды при разном составе портфеля, и витрина перестала бы быть
    # воспроизводимой.
    for ticker in _SPEC:
        final_price, drift, vol, beta = _SPEC[ticker]
        idio = rng.standard_normal(n) * (vol / np.sqrt(_TRADING_DAYS_PER_YEAR))
        # Рыночная компонента берётся БЕЗ своего дрейфа (он уже учтён в `drift`
        # актива) — иначе бета добавляла бы второй дрейф поверх собственного.
        mkt_shock = mkt_daily - mkt_spec[1] / _TRADING_DAYS_PER_YEAR
        daily = drift / _TRADING_DAYS_PER_YEAR + beta * mkt_shock + idio
        walk = np.exp(np.cumsum(daily))
        # Нормировка к заданному финальному уровню.  Умножение на константу не
        # меняет log-доходности (log(c·p_t / c·p_{t-1}) = log(p_t/p_{t-1})),
        # поэтому σ, беты, корреляции, CVaR и вся факторная модель инвариантны.
        prices = walk * (final_price / walk[-1])
        if ticker in wanted:
            cols[ticker] = prices

    df = pd.DataFrame(cols, index=index)
    if days is not None and days > 0:
        df = df.iloc[-min(int(days), len(df)):]
    return df


def _final_prices() -> dict[str, float]:
    """Финальные цены витрины — источник правды для расчёта количеств."""
    return {t: float(v[0]) for t, v in _SPEC.items()}


def build_demo_portfolio() -> pd.DataFrame:
    """
    Портфель витрины в том же контракте, что отдаёт ``FreedomConnector``.

    Колонки и их семантика совпадают с ``FreedomConnector._to_dataframe`` —
    ниже по конвейеру демо неотличимо от брокерского фрейма, поэтому никакой
    отдельной ветки в движке не нужно.
    """
    from finance.broker_api import classify_instrument
    from finance.investment_logic import MAC3RiskEngine

    # Количество выводится из ЦЕЛЕВОЙ ДОЛИ и детерминированной финальной цены,
    # поэтому аллокация витрины ровно такая, как задумана (§DEMO_ALLOCATION).
    engine_cls = MAC3RiskEngine
    finals = _final_prices()
    rows: list[dict] = []
    for ticker, weight, cost_ratio in DEMO_ALLOCATION:
        resolved = engine_cls.TICKER_MAP.get(ticker.upper(), None)
        if resolved is None:
            resolved = ticker if ("." in ticker or ticker.endswith("-USD")) else f"{ticker}.US"
        final_price = finals[resolved]
        qty = DEMO_TOTAL_VALUE * weight / final_price
        # Округление количества — до вида, правдоподобного для брокерской выписки.
        qty = round(qty, 4 if final_price > 1_000 else 2)
        rows.append({
            "Ticker":               ticker,
            "Quantity":             float(qty),
            "Purchase_Price":       round(final_price * cost_ratio, 2),
            # Цена берётся из матрицы витрины (приоритет 2 в analyze_all).
            # Ставить сюда Purchase_Price НЕЛЬЗЯ — позиция уйдёт в
            # broker_priced_only и выпадет из факторной модели.
            "Broker_Current_Price": None,
            "Asset_Type":           classify_instrument(ticker),
            "Raw_Ticker":           ticker,
        })
    for currency, amount in DEMO_CASH:
        rows.append({
            "Ticker":               currency,
            "Quantity":             float(amount),
            "Purchase_Price":       1.0,
            "Broker_Current_Price": 1.0,
            "Asset_Type":           "Кэш",
            "Raw_Ticker":           currency,
        })

    df = pd.DataFrame(rows, columns=[
        "Ticker", "Quantity", "Purchase_Price", "Broker_Current_Price",
        "Asset_Type", "Raw_Ticker",
    ])
    df.attrs["_ramp_is_mock"] = True
    df.attrs["_ramp_source"] = "demo"
    return df


