"""
Демо-витрина RAMP — детерминированный портфель и детерминированные цены.

Назначение
──────────
Демо существует ровно для одного: показать будущему клиенту, КАК выглядит отчёт,
до того как он подключит брокера или введёт портфель руками.  Отсюда три
жёстких требования, которых прежняя реализация не выполняла:

  1. **Одинаково у всех и всегда.**  Отчёт по демо обязан быть побитово одним и
     тем же для любого пользователя в любой день — иначе это не витрина, а
     случайный слепок рынка.  Прежнее демо брало ЖИВЫЕ цены, поэтому два
     человека в один день видели разное, а один человек в разные дни — тем более.
  2. **Всегда полный.**  Витрина не имеет права зависеть от доступности
     провайдера, квоты ключа или сетевого сбоя: демо считается ЛОКАЛЬНО и
     не делает ни одного сетевого вызова.
  3. **Показательный состав.**  Портфель должен задействовать максимум секций
     отчёта: несколько секторов, облигации, золото, EM-бумага, крипто и кэш —
     иначе половина панелей отчёта на витрине пустует.

Почему цены синтетические, а не «замороженный снимок рынка»
────────────────────────────────────────────────────────────
Замороженный снимок реальных котировок — это дистрибуция биржевых данных, со
своими лицензионными условиями (та же причина, по которой данные Freedom API
нельзя показывать не-клиентам, см. `docs/roadmap/manual_portfolio/PHASE_00_CONTRACT.md
§3a`).  Витрине реальные котировки не нужны: ей нужны ПРАВДОПОДОБНЫЕ ряды, на
которых движок покажет свою работу.  Поэтому ряды порождаются факторной моделью
с фиксированным зерном — они детерминированы, компактны (файла с данными нет
вообще) и свободны от каких-либо прав на данные.

Ряды строятся ТОЙ ЖЕ факторной структурой, которую движок потом оценивает:
    r_i(t) = β_i · r_mkt(t) + ε_i(t),   ε_i ~ N(0, σ_i²/252)
Это даёт невырожденную положительно определённую ковариацию, устойчивые беты и
осмысленную секторную корреляцию — то есть отчёт на витрине выглядит так же,
как на настоящем портфеле, а не как на шуме.

Детерминизм и его защита
────────────────────────
Используется `np.random.Generator(np.random.PCG64(seed))` — поток PCG64
задокументирован NumPy как воспроизводимый.  На случай, если это когда-нибудь
изменится, в `tests/test_phase35_demo_showcase.py` есть канареечный тест на
конкретные значения: он упадёт сразу, а не тихо изменит витрину.

Обновление витрины
──────────────────
`DEMO_END_DATE` заморожена сознательно — она и обеспечивает «всегда одинаково».
Раз в несколько месяцев её стоит подвинуть вперёд (одна строка), иначе витрина
начнёт выглядеть исторической.  Проверка свежести (B-4) для демо не применяется:
CoVe подписывает источник как фиксированный снимок витрины, а не как живой фид.
"""

from __future__ import annotations

