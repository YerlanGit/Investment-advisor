"""Имена продукта — SSOT (`§−101`).

Зачем отдельный модуль
──────────────────────
Проект переименовывается второй раз (RAMP → OMBRIOS), и первый переезд
показал цену размазанного имени: одно только слово `ramp` дало в репозитории
ЧЕТЫРЕ несовместимых класса совпадений — бренд, имя ресурса GCP, ключ
контракта `df.attrs['_ramp_*']` и математический хелпер `scoring._ramp`.
Замена по слову тогда сломала бы расчёт риск-индекса
(`docs/roadmap/rename_ombrios/README.md §0`).

Здесь живут ТОЛЬКО те имена, которые видит пользователь. Ни имена ресурсов
GCP, ни ключи контрактов сюда не попадают и попадать не должны: у них другая
цена изменения и другой владелец.

Четыре имени и почему они РАЗНЫЕ
────────────────────────────────
* `project_name()` — платформа целиком: **OMBRIOS**. Так продукт называется
  в описании тарифов и в дисклеймере.
* `bot_name()` — бот, с которым говорит пользователь: **OMBRI**. Короткое
  имя, им подписаны приветствие, помощь и поддержка.
* `bot_username()` — Telegram-хэндл БЕЗ `@`. Он едет в отчёт и превращается
  в deep-link `t.me/<хэндл>?start=scn_<n>`, поэтому обязан совпадать с
  ЖИВЫМ ботом: отчёт статичен, и ошибка в нём не правится задним числом.
* `support_contact()` — контакт поддержки С `@`. Аккаунта пока нет; имя
  выбрано заранее, чтобы завести его одним действием.

Всё читается из окружения при ВЫЗОВЕ, а не при импорте: тесту достаточно
подменить переменную, а не перезагружать модуль. Дефолты — рабочие
значения, поэтому забытая переменная даёт правильное имя, а не пустоту.

🔴 Модуль stdlib-only и лежит в корне `src/` (слой L0): его импортируют и
`tg_bot` (L4), и `pdf_payload` (L3), и `profile_manager` — импорт вниз, петли
невозможны.
"""

from __future__ import annotations

import os

__all__ = [
    "PROJECT_NAME_DEFAULT", "BOT_NAME_DEFAULT",
    "BOT_USERNAME_DEFAULT", "SUPPORT_CONTACT_DEFAULT",
    "project_name", "bot_name", "bot_username", "support_contact",
]

#: Платформа. Полное название проекта.
PROJECT_NAME_DEFAULT = "OMBRIOS"
#: Бот. Короткое имя того, с кем пользователь говорит.
BOT_NAME_DEFAULT = "OMBRI"
#: Telegram-хэндл БЕЗ `@`. 🔴 Меняется ВМЕСТЕ с токеном бота, а не отдельно:
#: разъехались — кнопка «Применить идею» ведёт к боту, которого не опрашивают.
BOT_USERNAME_DEFAULT = "Ombri_bot"
#: Контакт поддержки С `@`. Аккаунт ещё не заведён (`§−101`).
SUPPORT_CONTACT_DEFAULT = "@OMBRI_support_bot"


def _env(name: str, default: str) -> str:
    """Непустое значение из окружения, иначе дефолт.

    Пустая строка трактуется как «не задано»: `--set-env-vars` в Cloud Run
    легко оставляет переменную объявленной, но пустой, и имя продукта не то
    место, где пустота лучше дефолта.
    """
    return str(os.getenv(name, "") or "").strip() or default


def project_name() -> str:
    """Название платформы — `BRAND_PROJECT_NAME`, по умолчанию `OMBRIOS`."""
    return _env("BRAND_PROJECT_NAME", PROJECT_NAME_DEFAULT)


def bot_name() -> str:
    """Название бота — `BRAND_BOT_NAME`, по умолчанию `OMBRI`."""
    return _env("BRAND_BOT_NAME", BOT_NAME_DEFAULT)


def bot_username() -> str:
    """Telegram-хэндл БЕЗ `@` — `BOT_USERNAME`, по умолчанию `Ombri_bot`.

    Имя переменной сохранено прежним: она уже описана в доках, читается
    отчётом и задаётся в деплое. Переименовывать её заодно значило бы
    поменять две вещи там, где ломается одна.
    """
    return _env("BOT_USERNAME", BOT_USERNAME_DEFAULT).lstrip("@")


def support_contact() -> str:
    """Контакт поддержки С `@` — `SUPPORT_CONTACT`."""
    value = _env("SUPPORT_CONTACT", SUPPORT_CONTACT_DEFAULT)
    return value if value.startswith("@") else "@" + value
